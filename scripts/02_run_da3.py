"""[env: da3] DA3 on frame 0, cam01..cam20 (cam00 = test view, NEVER an input), GT poses as condition.

Saves everything needed downstream into one .pt so we never re-run the model:
  depth/conf (aligned to GT pose scale), intrinsics (processed res), GT extrinsics,
  processed_images, raw predicted extrinsics (before alignment), and the raw
  per-pixel gaussians (means/scales/rotations/harmonics/opacities, ordered (v h w)).

Why raw gaussians instead of DA3's gs_ply export: the export prunes pixels (breaks the
pixel <-> gaussian correspondence we use for alignment) and keeps SH DC only.
"""
import argparse
import json
import os
import sys
import time
from pathlib import Path

import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.colmap_io import load_cameras
from common.camera_selection import read_views_file, validate_view_names
from common.timing import gpu_exclusive, gpu_name


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--frame_dir", required=True)
    ap.add_argument("--images", default="images_2")
    ap.add_argument("--test_cam", default="cam00")
    views = ap.add_mutually_exclusive_group()
    views.add_argument("--views", nargs="+", help="Ordered DA3 input camera names")
    views.add_argument("--views-file", help="JSON generated by 12_select_cameras.py")
    ap.add_argument("--exclude", nargs="*", default=[], help="Additional held-out cameras")
    ap.add_argument("--dry-run", action="store_true", help="Validate cameras without loading DA3 or using a GPU")
    ap.add_argument("--model", default=os.environ.get("DA3_MODEL", "depth-anything/DA3-GIANT-1.1"))
    ap.add_argument("--process_res", type=int, default=504)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    requested, selection = args.views, {}
    if args.views_file:
        requested, selection = read_views_file(args.views_file)
    excluded = sorted(set([args.test_cam] + args.exclude + selection.get("excluded_cameras", [])))
    if requested is not None:
        validate_view_names(requested, excluded)
    cams = load_cameras(args.frame_dir, args.images, exclude=excluded, only=requested)
    if requested is not None:
        by_name = {camera.name: camera for camera in cams}
        validate_view_names(requested, excluded, by_name)
        cams = [by_name[name] for name in requested]
    names = [c.name for c in cams]
    validate_view_names(names, excluded)
    if selection.get("n_views", len(names)) != len(names):
        raise ValueError("Views-file n_views differs from selected camera count")
    if selection.get("anchor", names[0]) != names[0]:
        raise ValueError("Views-file anchor must be the first DA3 input camera")
    print(f"{len(cams)} input views: {names}")
    if args.dry_run:
        print(json.dumps(dict(names=names, n_views=len(names), excluded_cameras=excluded,
                              selection=selection, dry_run=True), indent=2))
        return
    if os.path.exists(args.out):
        raise FileExistsError(f"Raw output already exists: {args.out}; use a new condition/output name")
    import torch
    from depth_anything_3.api import DepthAnything3

    images = [c.image_path for c in cams]
    ext = np.stack([c.w2c for c in cams]).astype(np.float32)
    K = np.stack([c.K for c in cams]).astype(np.float32)

    t_load = time.time()
    model = DepthAnything3.from_pretrained(args.model).to("cuda").eval()
    torch.cuda.synchronize()
    model_load_sec = time.time() - t_load
    exclusive = gpu_exclusive()
    if exclusive is False:
        print("WARNING: GPU busy -> DA3 time will be marked non-exclusive (stop the queue for the timed run)")

    captured = {}
    orig = model._align_to_input_extrinsics_intrinsics

    def hook(extrinsics, intrinsics, prediction, *a, **k):
        if prediction.extrinsics is not None:
            captured["pred_ext_raw"] = np.array(prediction.extrinsics).copy()
        return orig(extrinsics, intrinsics, prediction, *a, **k)

    model._align_to_input_extrinsics_intrinsics = hook

    torch.cuda.synchronize(); torch.cuda.reset_peak_memory_stats()
    t0 = time.time()
    with torch.inference_mode():
        pred = model.inference(images, extrinsics=ext, intrinsics=K, align_to_input_ext_scale=True,
                               infer_gs=True, process_res=args.process_res, ref_view_strategy="first")
    torch.cuda.synchronize()
    dt = time.time() - t0
    g = pred.gaussians
    assert g is not None, "no gaussians: does this checkpoint have a GS head? (DA3-GIANT / NESTED only)"

    f = lambda x: x.detach().float().cpu()[0] if x.dim() >= 2 and x.shape[0] == 1 else x.detach().float().cpu()
    out = dict(
        names=names, selection=selection, excluded_cameras=excluded,
        model=args.model, process_res=args.process_res, time_sec=dt,
        peak_mem_gb=torch.cuda.max_memory_allocated() / 1e9,
        depth=torch.from_numpy(np.asarray(pred.depth, dtype=np.float32)),
        conf=None if pred.conf is None else torch.from_numpy(np.asarray(pred.conf, dtype=np.float32)),
        intrinsics=torch.from_numpy(np.asarray(pred.intrinsics, dtype=np.float32)),
        extrinsics=torch.from_numpy(np.asarray(pred.extrinsics, dtype=np.float32)),
        gt_extrinsics=torch.from_numpy(ext),
        processed_images=torch.from_numpy(np.asarray(pred.processed_images)),
        pred_ext_raw=None if "pred_ext_raw" not in captured else torch.from_numpy(captured["pred_ext_raw"].astype(np.float32)),
        gs_means=f(g.means), gs_scales=f(g.scales), gs_rotations=f(g.rotations),
        gs_harmonics=f(g.harmonics), gs_opacities=f(g.opacities),
    )
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    torch.save(out, args.out)
    V, H, W = out["depth"].shape
    info = {k: (list(v.shape) if torch.is_tensor(v) else v) for k, v in out.items()}
    print(json.dumps(info, indent=1, default=str))
    print(f"V*H*W = {V * H * W}, gaussians = {out['gs_means'].shape[0]}  (should match)")
    print(f"DA3 inference {dt:.1f}s (model load {model_load_sec:.1f}s, not counted), peak mem {out['peak_mem_gb']:.1f} GB")
    with open(os.path.splitext(args.out)[0] + "_meta.json", "w") as fp:
        json.dump(dict(model=args.model, process_res=args.process_res, time_sec=dt, model_load_sec=model_load_sec,
                       gpu=gpu_name(), gpu_exclusive=exclusive, peak_mem_gb=out["peak_mem_gb"],
                       n_views=len(names), names=names, selection=selection,
                       excluded_cameras=excluded, depth_hw=[H, W],
                       n_gaussians=int(out["gs_means"].shape[0]),
                       note="time_sec = model.inference() wall clock (image loading/preprocess + forward + "
                            "pose alignment), cold first call, weights already on GPU"), fp, indent=1)


if __name__ == "__main__":
    main()
